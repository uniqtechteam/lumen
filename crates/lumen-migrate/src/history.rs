//! The migrations folder and the `_prisma_migrations` table, in Prisma's formats so a project can
//! move between lumen and Prisma: `migrations/<YYYYMMDDHHMMSS>_<name>/migration.sql`,
//! `migrations/migration_lock.toml`, and the same table columns and checksums.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use sha2::{Digest, Sha256};
use sqlx::postgres::PgConnection;
use sqlx::{AssertSqlSafe, Row};

use crate::MigrateError;

/// The file that records which database the migrations are for.
pub const LOCK_FILE: &str = "migration_lock.toml";

/// Prisma's advisory lock key, so lumen and Prisma never deploy at the same moment.
pub const ADVISORY_LOCK_KEY: i64 = 72_707_369;

/// One migration folder.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LocalMigration {
    /// The folder name, `20261115093000_init`.
    pub name: String,
    /// The SQL.
    pub script: String,
}

impl LocalMigration {
    /// The SHA-256 of the script, as Prisma stores it.
    #[must_use]
    pub fn checksum(&self) -> String {
        checksum(&self.script)
    }

    /// Whether `stored` is this script's checksum, allowing for CRLF/LF differences (a file
    /// checked out on Windows is the same migration).
    #[must_use]
    pub fn matches(&self, stored: &str) -> bool {
        stored == self.checksum()
            || stored == checksum(&self.script.replace("\r\n", "\n"))
            || stored == checksum(&self.script.replace('\n', "\r\n"))
    }
}

/// Lower-case hex SHA-256.
#[must_use]
pub fn checksum(text: &str) -> String {
    Sha256::digest(text.as_bytes())
        .iter()
        .fold(String::with_capacity(64), |mut hex, b| {
            let _ = write!(hex, "{b:02x}");
            hex
        })
}

/// The migrations in `dir`, oldest first. A missing folder has none.
///
/// # Errors
/// When a migration folder cannot be read.
pub fn read_dir(dir: &Path) -> Result<Vec<LocalMigration>, MigrateError> {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return Ok(Vec::new());
    };
    let mut out = Vec::new();
    for entry in entries.flatten() {
        let path = entry.path();
        let sql = path.join("migration.sql");
        if !path.is_dir() || !sql.exists() {
            continue;
        }
        let script = std::fs::read_to_string(&sql)
            .map_err(|e| MigrateError::new(format!("cannot read {}: {e}", sql.display())))?;
        out.push(LocalMigration {
            name: entry.file_name().to_string_lossy().into_owned(),
            script,
        });
    }
    out.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(out)
}

/// Write `migration_lock.toml` if it is missing, and refuse a folder made for another database.
///
/// # Errors
/// When the folder is for another provider, or cannot be written.
pub fn ensure_lock(dir: &Path, provider: &str) -> Result<(), MigrateError> {
    let path = dir.join(LOCK_FILE);
    if let Ok(text) = std::fs::read_to_string(&path) {
        let found = text.lines().find_map(|l| {
            let rest = l
                .trim()
                .strip_prefix("provider")?
                .trim_start()
                .strip_prefix('=')?;
            Some(rest.trim().trim_matches('"').to_owned())
        });
        return match found {
            Some(p) if p == provider => Ok(()),
            Some(p) => Err(MigrateError::new(format!(
                "the migrations in {} are for `{p}`, but the schema uses `{provider}`; start a new migrations folder for the new database",
                dir.display()
            ))),
            None => Ok(()),
        };
    }
    std::fs::create_dir_all(dir)
        .map_err(|e| MigrateError::new(format!("cannot create {}: {e}", dir.display())))?;
    let text = format!(
        "# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = \"{provider}\"\n"
    );
    std::fs::write(&path, text)
        .map_err(|e| MigrateError::new(format!("cannot write {}: {e}", path.display())))
}

/// Days since 1970-01-01 to (year, month, day), proleptic Gregorian (Howard Hinnant's algorithm).
fn civil(days: i64) -> (i64, u32, u32) {
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = u32::try_from(doy - (153 * mp + 2) / 5 + 1).unwrap_or(1);
    let month = u32::try_from(if mp < 10 { mp + 3 } else { mp - 9 }).unwrap_or(1);
    let year = yoe + era * 400 + i64::from(month <= 2);
    (year, month, day)
}

/// `YYYYMMDDHHMMSS` in UTC, the prefix of a migration folder.
#[must_use]
pub fn timestamp(unix_seconds: i64) -> String {
    let (y, m, d) = civil(unix_seconds.div_euclid(86_400));
    let secs = unix_seconds.rem_euclid(86_400);
    format!(
        "{y:04}{m:02}{d:02}{:02}{:02}{:02}",
        secs / 3600,
        secs % 3600 / 60,
        secs % 60
    )
}

/// Seconds since 1970 for a `YYYYMMDDHHMMSS` prefix (the inverse of [`timestamp`]).
#[must_use]
pub fn parse_timestamp(text: &str) -> Option<i64> {
    if text.len() != 14 || !text.bytes().all(|b| b.is_ascii_digit()) {
        return None;
    }
    let n = |r: std::ops::Range<usize>| text[r].parse::<i64>().ok();
    let (y, m, d) = (n(0..4)?, n(4..6)?, n(6..8)?);
    let (hh, mm, ss) = (n(8..10)?, n(10..12)?, n(12..14)?);
    // days from civil (Howard Hinnant)
    let y = if m <= 2 { y - 1 } else { y };
    let era = y.div_euclid(400);
    let yoe = y - era * 400;
    let mp = if m > 2 { m - 3 } else { m + 9 };
    let doy = (153 * mp + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    let days = era * 146_097 + doe - 719_468;
    Some(days * 86_400 + hh * 3600 + mm * 60 + ss)
}

/// A folder name for a new migration: the timestamp, then the name in snake case (at most 200
/// characters, as Prisma allows).
#[must_use]
pub fn folder_name(unix_seconds: i64, name: &str) -> String {
    let clean: String = name
        .trim()
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect();
    let clean = clean.trim_matches('_');
    let mut out = format!(
        "{}_{}",
        timestamp(unix_seconds),
        if clean.is_empty() { "migration" } else { clean }
    );
    out.truncate(200);
    out
}

/// One row of `_prisma_migrations`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AppliedMigration {
    /// The folder name.
    pub name: String,
    /// The checksum stored when it ran.
    pub checksum: String,
    /// Whether it finished.
    pub finished: bool,
    /// Whether it was marked rolled back.
    pub rolled_back: bool,
    /// The error text, if it failed.
    pub logs: Option<String>,
}

const CREATE_TABLE: &str = r#"CREATE TABLE IF NOT EXISTS "_prisma_migrations" (
    "id"                    VARCHAR(36) PRIMARY KEY NOT NULL,
    "checksum"              VARCHAR(64) NOT NULL,
    "finished_at"           TIMESTAMPTZ,
    "migration_name"        VARCHAR(255) NOT NULL,
    "logs"                  TEXT,
    "rolled_back_at"        TIMESTAMPTZ,
    "started_at"            TIMESTAMPTZ NOT NULL DEFAULT now(),
    "applied_steps_count"   INTEGER NOT NULL DEFAULT 0
)"#;

/// Create the history table if it is missing (same columns as Prisma's).
///
/// # Errors
/// When the statement fails.
pub async fn ensure_table(conn: &mut PgConnection) -> Result<(), sqlx::Error> {
    sqlx::raw_sql(CREATE_TABLE).execute(conn).await.map(|_| ())
}

/// The recorded migrations, oldest first; none when the table does not exist yet.
///
/// # Errors
/// When the query fails.
pub async fn applied(conn: &mut PgConnection) -> Result<Vec<AppliedMigration>, sqlx::Error> {
    let exists: bool = sqlx::query_scalar("select to_regclass('_prisma_migrations') is not null")
        .fetch_one(&mut *conn)
        .await?;
    if !exists {
        return Ok(Vec::new());
    }
    let rows = sqlx::query(
        "select migration_name, checksum, finished_at is not null as finished, \
         rolled_back_at is not null as rolled_back, logs \
         from _prisma_migrations order by started_at, migration_name",
    )
    .fetch_all(&mut *conn)
    .await?;
    rows.iter()
        .map(|r| {
            Ok(AppliedMigration {
                name: r.try_get("migration_name")?,
                checksum: r.try_get("checksum")?,
                finished: r.try_get("finished")?,
                rolled_back: r.try_get("rolled_back")?,
                logs: r.try_get("logs")?,
            })
        })
        .collect()
}

/// Run one migration and record it: the row is written before the script runs and finished after,
/// so a crash in the middle leaves a failed row that `status` reports.
///
/// # Errors
/// When the script fails (its error is also stored in `logs`), or the history cannot be written.
pub async fn apply(
    conn: &mut PgConnection,
    migration: &LocalMigration,
) -> Result<(), MigrateError> {
    let id: String = sqlx::query_scalar(
        "insert into _prisma_migrations (id, checksum, migration_name, started_at, applied_steps_count) \
         values (gen_random_uuid()::text, $1, $2, now(), 0) returning id",
    )
    .bind(migration.checksum())
    .bind(&migration.name)
    .fetch_one(&mut *conn)
    .await?;
    // the script is a migration file from the project's own migrations folder
    match sqlx::raw_sql(AssertSqlSafe(migration.script.clone()))
        .execute(&mut *conn)
        .await
    {
        Ok(_) => {
            sqlx::query("update _prisma_migrations set finished_at = now(), applied_steps_count = 1 where id = $1")
                .bind(&id)
                .execute(&mut *conn)
                .await?;
            Ok(())
        }
        Err(e) => {
            let logs = e.to_string();
            sqlx::query("update _prisma_migrations set logs = $1 where id = $2")
                .bind(&logs)
                .bind(&id)
                .execute(&mut *conn)
                .await?;
            Err(MigrateError::new(format!(
                "the migration `{}` failed: {logs}\nFix the database or the migration, then mark it with `lumen migrate resolve`",
                migration.name
            )))
        }
    }
}

/// Where a project keeps its migrations: next to the schema file, like Prisma.
#[must_use]
pub fn default_dir(schema_path: &Path) -> PathBuf {
    schema_path
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .join("migrations")
}

#[cfg(test)]
mod tests {
    use super::{LocalMigration, checksum, folder_name, timestamp};

    #[test]
    fn timestamps_and_names() {
        assert_eq!(timestamp(0), "19700101000000");
        assert_eq!(timestamp(1_763_199_000), "20251115093000");
        assert_eq!(
            folder_name(1_763_199_000, "Add user emails!"),
            "20251115093000_add_user_emails"
        );
        assert_eq!(folder_name(1_763_199_000, "  "), "20251115093000_migration");
        for t in [0, 1_763_199_000, 951_782_400, 4_102_444_799] {
            assert_eq!(super::parse_timestamp(&timestamp(t)), Some(t));
        }
    }

    #[test]
    fn checksums_ignore_line_endings() {
        assert_eq!(
            checksum("abc"),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        let m = LocalMigration {
            name: "x".into(),
            script: "a;\r\nb;\r\n".into(),
        };
        assert!(m.matches(&checksum("a;\nb;\n")));
        assert!(!m.matches(&checksum("other")));
    }
}
